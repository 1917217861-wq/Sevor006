# === 固定机位视觉映射参数 (2026-09-27 现场标定, 屏幕距激光笔1.0m) ===
# 粗对准公式: angle = HOME_ANGLE + (pixel - CAM_HOME) * PIX2DEG * SPOT_DIR
# HOME_ANGLE 恒为 (0,0): 每次上电"对中方框中心 -> 按设零点", 当前位姿即定义为0度
#   ❌ 为什么HOME不标定了: F32C多圈零点掉电不保持(实测坐实) —— 断电前后 ctr 完全不变
#   (268,157), 而 laser 从(516,144)跑到画面外: 同一绝对角在断电前后指向完全不同的方向.
#   所以改为"每会话清零一次"; 标定只剩 CAM_HOME + PIX2DEG, 而这两个只跟相机/屏幕
#   几何有关, 场地不动就一直有效(断电也不影响)
# 标定方法: 标定页(flag=4)微调对中 + "测X/测Y"自动摆±5°测PIX2DEG
# 2026-09-27 实测记录(1.0m, 场地重装后):
#   laser=(268,155) 对中方框中心后设零点 -> CAM_HOME=(268,155)
#   (与此时 ctr=(268,157) 只差2px -> A4贴得正, 肉眼对中准)
#   测X: PIX2DEG=0.1563 dx=64 dy=-4  (10°摆动光斑走64px, 串扰6%)
#   测Y: PIX2DEG=0.1724 dx=-1 dy=-58  (走58px, 串扰2%)
#   dx>0 => SPOT_DIR_X=+1 ; dy<0 => SPOT_DIR_Y=-1
# 判决尺(1.0m): 1°≈1.745cm; 10°摆动@垂直入射≈17.5cm -> 64px => 3.66px/cm(X),
#   58px => 3.32(Y); A4宽29.7cm=89px => 3.0. 取 ≈3.3px/cm
#   => 2cm容差≈6~7px, 3cm≈10px, A4胶带宽1.8cm≈6px
# 🔴 瓶颈: 场地(软布+A4)自身会漂 4~8px = 1.2~2.4cm, 与2cm容差同量级
#   -> 必须换硬质背板/绷紧布/A4四角粘死, 否则基本1是赌运气
CAM_HOME_PX  = 315     # "0度"对应的像素 = 设零点那一刻的A4中心ctr
CAM_HOME_PY  = 191     # 🔧 2026-10-01 起由"设零点"按钮**自动更新**(见 main.calib_zero),
                       #    这里只是**上电到第一次设零点之间**的兜底值.
                       #    ★为什么必须自动更新: 前馈粗对准 = (px - CAM_HOME)*PIX2DEG*SPOT_DIR,
                       #      而设零点把"光斑压在ctr上"的位姿定义成0度 -> 像素原点必须=ctr.
                       #      实测: A4四角粘死后 ctr 从(273,161)挪到(315,191), 这个常量没跟着走
                       #      -> 前馈整体偏 42/30px≈15cm, 整圈跟这15cm打架, maxerr 154px.
                       #    ⚠️ 上电后没按设零点就跑, 用的就是这个兜底值 —— 场地一挪就过期
HOME_ANGLE_X = 0.0     # 恒为0: 每次上电对中后按"设零点"把当前位姿定义成0度
HOME_ANGLE_Y = 0.0     # (零点掉电不保持, 详见上面说明)
PIX2DEG_X    = 0.1563  # 摄像头像素→X轴电机度 换算 (度/像素, 2026-09-27 1.0m实测)
PIX2DEG_Y    = 0.1724  # 摄像头像素→Y轴电机度 换算 (度/像素, 2026-09-27 1.0m实测)
SPOT_DIR_X   = 1       # X轴电机角增大时光斑向右 (实测验证)
SPOT_DIR_Y   = -1      # Y轴电机角增大时光斑向上 (实测验证)
SERVO_GAIN   = 0.4     # 视觉伺服修正增益: 每轮修正误差的这个比例.
                       # 0.8会震荡(视觉有~100ms延迟, 环路增益接近1就抖, 实测落点散布±10px);
                       # 0.4稳定收敛, 误差每轮×0.6, 300~600ms内到位
                       # 0=纯粗对准开环; 若嫌慢可升到0.5, 一抖就降回0.3
SERVO_GAIN_LAP = 0.35  # 边线/胶带(基本2/3/4)专用伺服增益, 与上面的复位增益解耦.
                       # ⚠️ 这是**运行时**变量: 断电重上就回到这个默认值, 检测页按 gain± 改的
                       #    不会被保存 —— 所以**现场调好的值必须写回这里**, 否则每次上电都要手按.
                       # 0.2 -> 0.35 (2026-10-01 实测): 0.20/0.35 都跑通(整圈 11.5~11.9s,
                       #    maxerr 7px/6px, err 常态 0~2px), 取 0.35 是因为**前置对位更快**
                       #    (起步那 1~2 秒就贴住起点), 峰值误差还略低.
                       # 2026-09-30 曾从 0.3 降到 0.2 治"左右抖" —— 那次判断错了: 抖的真因是
                       #    **画面里墙面反光被当成绿块**(假块), 增益只是放大它(越高拽得越狠).
                       #    反光遮住 + 加上光斑跳变门控(trajectory.SPOT_GATE_PX)之后, 0.35 很干净.
                       # 稳定性判据 k·d < π/2≈1.57 (d=环路延迟帧数); lap 每帧更新(d≈2), 0.35 稳.
                       # 抖 -> 先查假块(看 LAB 掩膜/读 traj.log 的 a 列), 别急着降增益

